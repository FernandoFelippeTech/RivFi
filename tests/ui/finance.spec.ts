test('OCR real com imagem sintética, múltiplos valores e nenhuma transmissão externa', async ({ page }) => {
  const external: string[] = []
  page.on('request', request => { if (/^https?:/.test(request.url()) && !request.url().startsWith('http://127.0.0.1:5173')) external.push(request.url()) })
  await page.goto('/tests/preview.html')
  const png = await page.evaluate(() => {
    const c = document.createElement('canvas'); c.width = 1100; c.height = 550
    const x = c.getContext('2d')!; x.fillStyle = '#fff'; x.fillRect(0,0,c.width,c.height); x.fillStyle = '#000'; x.font = '36px Arial'
    const d = new Intl.DateTimeFormat('pt-BR', { timeZone: 'America/Sao_Paulo' }).format(new Date())
    ;['COMPROVANTE FICTICIO', 'Destinatario: MERCADO TESTE', d, 'Total R$ 123,45', 'Saldo R$ 999,00'].forEach((s,i) => x.fillText(s,40,70+i*85))
    return c.toDataURL('image/png').split(',')[1]
  })
  await page.getByRole('button', { name: 'Ler comprovante', exact: true }).click()
  await page.locator('input[type=file]').setInputFiles({ name: 'comprovante-ficticio.png', mimeType: 'image/png', buffer: Buffer.from(png,'base64') })
  await expect(page.getByAltText('Prévia do comprovante selecionado')).toBeVisible()
  await page.getByRole('button', { name: 'Ler e revisar' }).click()
  await expect(page.getByText('REVISÃO DO COMPROVANTE')).toBeVisible({ timeout: 100000 })
  await expect(page.getByLabel('Valor (R$)', { exact: true })).toHaveValue('')
  await expect(page.getByRole('combobox', { name: 'Tipo', exact: true })).toHaveValue('')
  await page.getByRole('button', { name: 'R$ 123,45', exact: true }).click()
  await expect(page.getByLabel('Valor (R$)', { exact: true })).toHaveValue('123,45')
  await expect(page.getByText('Lançamento confirmado no Supabase.', { exact: true })).toHaveCount(0)
  expect(external).toEqual([])
})
