test('backup inválido é rejeitado, restauração requer confirmação e repetição não duplica', async ({ page }) => {
  await page.goto('/tests/preview.html')
  await page.getByRole('button', { name: 'Backup', exact: true }).click()
  await page.locator('input[type=file]').setInputFiles({ name: 'invalido.json', mimeType: 'application/json', buffer: Buffer.from('{"version":99}') })
  await expect(page.getByRole('alert')).toContainText('incompatível')
  const date = await page.evaluate(() => new Intl.DateTimeFormat('en-CA', { timeZone: 'America/Sao_Paulo', year: 'numeric', month: '2-digit', day: '2-digit' }).format(new Date()))
  const content = JSON.stringify({ format: 'rivfi', version: 1, exported_at: new Date().toISOString(), categories: [{ id: 'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa', name: 'Alimentação', keywords: ['mercado'], archived: false }], transactions: [{ id: 'ffffffff-ffff-4fff-8fff-ffffffffffff', amount_cents: 2345, date, description: 'Compra restaurada', kind: 'expense', category_id: 'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa' }] })
  const file = { name: 'backup.json', mimeType: 'application/json', buffer: Buffer.from(content) }
  await page.locator('input[type=file]').setInputFiles(file)
  await expect(page.getByText('Revise antes de restaurar')).toBeVisible()
  await expect(page.getByText('Restauração confirmada:', { exact: false })).toHaveCount(0)
  await page.getByRole('button', { name: 'Confirmar restauração' }).click()
  await expect(page.getByText('Restauração confirmada: 1 lançamento(s)', { exact: false })).toBeVisible()
  await page.locator('input[type=file]').setInputFiles(file)
  await expect(page.getByText('0 categoria(s) nova(s); 0 lançamento(s) novo(s); 1 já existente(s).', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Confirmar restauração' })).toBeDisabled()
})
