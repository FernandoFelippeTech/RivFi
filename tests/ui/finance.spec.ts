  await expect(page.getByText('Possível duplicidade', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Salvar mesmo assim' }).click()
  await expect(page.getByText('Compra igual legítima', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Editar Compra igual legítima' }).click()
  await page.getByLabel('Valor (R$)', { exact: true }).fill('99,99')
  await page.getByRole('button', { name: 'Confirmar e salvar', exact: true }).click()
